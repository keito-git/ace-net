"""
LLM-context baseline: per-example context generated by an external LLM.

Context sentences are generated offline and provided as a JSON file, either as
a flat mapping {text: context} or as a split dict {"train": [{"text", "context",
...}], "test": [...]}. For each example the context is prepended to the input:
  "Context: {llm_context} Text: {original_text}"  (truncated to max_length).

Fair comparison: same backbone, hyperparameters, and seeds as the DeBERTa
baseline. Context is generated once and reused across all seeds.
"""
import json
import os
from dataclasses import dataclass
from typing import Any, Dict, List

import numpy as np
import torch
from transformers import (
    AutoTokenizer,
    DebertaV2Config,
    EarlyStoppingCallback,
    Trainer,
    TrainingArguments,
)

from src.baselines.deberta_baseline import (
    BACKBONE,
    BaselineConfig,
    _build_compute_metrics,
    _tokenize_records,
)
from src.data.base_loader import BaseEmotionLoader
from src.eval.metrics import compute_all_metrics, save_metrics_json
from src.models.deberta_classifier import DeBERTaEmotionClassifier
from src.utils.env_log import log_environment
from src.utils.seed import set_seed


@dataclass
class LLMContextConfig:
    """LLM-context baseline configuration."""
    prefix: str = "Context: "
    infix: str = " Text: "


def load_context_mapping(context_file: str) -> Dict[str, str]:
    """
    Load the LLM context file and return a text->context mapping. Supports a
    flat dict, a split dict with 'train'/'val'/'test' lists, or a list of
    {'text', 'context'} items.
    """
    with open(context_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    if isinstance(data, dict) and ("train" in data or "test" in data):
        mapping = {}
        for split in ["train", "val", "test"]:
            for item in data.get(split, []):
                if isinstance(item, dict) and "text" in item and "context" in item:
                    mapping[item["text"].strip()] = item["context"].strip()
        return mapping
    elif isinstance(data, dict):
        return {k.strip(): v.strip() for k, v in data.items()}
    elif isinstance(data, list):
        return {
            item["text"].strip(): item["context"].strip()
            for item in data
            if isinstance(item, dict) and "text" in item and "context" in item
        }
    else:
        raise ValueError(f"Unrecognized context file format in: {context_file}")


def augment_with_llm_context(
    records: List[Dict[str, Any]],
    context_mapping: Dict[str, str],
    llm_cfg: LLMContextConfig,
    split_name: str = "?",
    verbose: bool = True,
) -> List[Dict[str, Any]]:
    """
    Prepend the LLM-generated context to each record when available. Records
    without a matching context are passed through unchanged (with a warning).
    """
    augmented = []
    n_missing = 0

    for i, rec in enumerate(records):
        original_text = rec["text"]
        ctx = context_mapping.get(original_text.strip())

        if ctx:
            new_text = llm_cfg.prefix + ctx + llm_cfg.infix + original_text
        else:
            n_missing += 1
            new_text = original_text

        augmented.append({**rec, "text": new_text, "_original_text": original_text})

        if verbose and i < 3 and ctx:
            print(f"  [{split_name}] Example {i}: {new_text[:100]}...")

    if n_missing > 0:
        pct = 100 * n_missing / len(records)
        print(f"  WARNING [{split_name}]: {n_missing}/{len(records)} ({pct:.1f}%) records "
              f"have no LLM context. Passed through unchanged.")

    return augmented


def run_llm_context_baseline(
    loader: BaseEmotionLoader,
    cfg: BaselineConfig,
    llm_cfg: LLMContextConfig,
    context_file: str,
    seed: int,
) -> Dict[str, float]:
    """
    Train DeBERTa on LLM-context augmented inputs.

    cfg must be identical to the DeBERTa baseline for a fair comparison.
    context_file is the LLM context JSON. Returns the test-set metrics.
    """
    set_seed(seed)

    run_dir = os.path.join(cfg.output_dir, f"seed_{seed}")
    os.makedirs(run_dir, exist_ok=True)

    log_environment(
        seed=seed,
        dataset_name=loader.__class__.__name__,
        output_dir=run_dir,
        extra={"method": "LLMContext", "context_file": context_file},
    )

    print(f"  Loading LLM context from: {context_file}")
    context_mapping = load_context_mapping(context_file)
    print(f"  Context mapping size: {len(context_mapping)} entries")

    tokenizer = AutoTokenizer.from_pretrained(cfg.model_name)
    train_records, val_records, test_records = loader.load_splits()

    train_aug = augment_with_llm_context(train_records, context_mapping, llm_cfg, "train")
    val_aug = augment_with_llm_context(val_records, context_mapping, llm_cfg, "val", verbose=False)
    test_aug = augment_with_llm_context(test_records, context_mapping, llm_cfg, "test", verbose=False)

    train_ds = _tokenize_records(
        train_aug, tokenizer, cfg.max_length, loader.is_multilabel, loader.n_labels
    )
    val_ds = _tokenize_records(
        val_aug, tokenizer, cfg.max_length, loader.is_multilabel, loader.n_labels
    )
    test_ds = _tokenize_records(
        test_aug, tokenizer, cfg.max_length, loader.is_multilabel, loader.n_labels
    )

    model_config = DebertaV2Config.from_pretrained(cfg.model_name)
    model_config.num_labels = loader.n_labels
    model_config.problem_type = (
        "multi_label_classification" if loader.is_multilabel
        else "single_label_classification"
    )
    model = DeBERTaEmotionClassifier.from_pretrained(
        cfg.model_name, config=model_config, ignore_mismatched_sizes=True,
    )

    use_fp16 = cfg.fp16 and torch.cuda.is_available()
    training_args = TrainingArguments(
        output_dir=run_dir,
        num_train_epochs=cfg.num_epochs,
        per_device_train_batch_size=cfg.batch_size,
        per_device_eval_batch_size=cfg.batch_size,
        learning_rate=cfg.lr,
        warmup_ratio=cfg.warmup_ratio,
        weight_decay=cfg.weight_decay,
        max_grad_norm=cfg.gradient_clip_norm,
        eval_strategy="epoch",
        save_strategy="epoch",
        load_best_model_at_end=True,
        metric_for_best_model=cfg.metric_for_best_model,
        greater_is_better=True,
        fp16=use_fp16,
        dataloader_num_workers=cfg.dataloader_num_workers,
        seed=seed,
        report_to="none",
        logging_steps=50,
        save_total_limit=1,
    )

    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=train_ds,
        eval_dataset=val_ds,
        compute_metrics=_build_compute_metrics(
            loader.is_multilabel, cfg.multilabel_threshold
        ),
        callbacks=[EarlyStoppingCallback(early_stopping_patience=cfg.early_stopping_patience)],
    )
    trainer.train()

    test_output = trainer.predict(test_ds)
    logits = test_output.predictions

    if loader.is_multilabel:
        probs = 1.0 / (1.0 + np.exp(-logits))
        y_pred = (probs >= cfg.multilabel_threshold).astype(int)
        y_true = np.stack([r["label"] for r in test_records])
    else:
        y_pred = np.argmax(logits, axis=-1)
        y_true = np.array([r["label"] for r in test_records])

    metrics = compute_all_metrics(y_true, y_pred, loader.label_names)
    metrics["seed"] = seed
    metrics["method"] = "LLMContext"

    save_metrics_json(metrics, os.path.join(run_dir, "test_metrics.json"))
    print(
        f"[seed={seed}] LLMContext macro_f1={metrics['macro_f1']:.4f}  "
        f"weighted_f1={metrics['weighted_f1']:.4f}"
    )
    return metrics
